"""
ml/train_model.py
------------------
Trains a Random Forest Classifier on the synthetic workload dataset
generated by data_generator.py.

Pipeline:
    1. Load (or auto-generate) workload_dataset.csv.
    2. Split 80 / 20 into train and test sets.
    3. Build a scikit-learn Pipeline: StandardScaler -> RandomForestClassifier.
    4. Fit, evaluate (classification report + confusion matrix), and persist
       the trained pipeline as 'ml/model.joblib'.

Usage:
    python -m ml.train_model
"""

import os
import sys
import numpy as np
import pandas as pd

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score

import joblib

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
_HERE = os.path.dirname(os.path.abspath(__file__))
DATA_PATH = os.path.join(_HERE, "..", "data", "workload_dataset.csv")
MODEL_PATH = os.path.join(_HERE, "model.joblib")

FEATURE_COLS = [
    "avg_burst_time",
    "burst_variance",
    "cpu_usage_pct",
    "io_burst_ratio",
    "process_count",
]
TARGET_COL = "workload_class"
CLASS_NAMES = ["CPU-bound", "I/O-bound", "Mixed"]

RANDOM_SEED = 42


# ---------------------------------------------------------------------------
# Helper: load or generate dataset
# ---------------------------------------------------------------------------

def _load_dataset(path: str) -> pd.DataFrame:
    if not os.path.exists(path):
        print("[Trainer] Dataset not found -- auto-generating...")
        from ml.data_generator import generate_dataset
        generate_dataset(save=True, output_path=path)

    df = pd.read_csv(path)
    missing = [c for c in FEATURE_COLS + [TARGET_COL] if c not in df.columns]
    if missing:
        raise ValueError(f"Dataset is missing expected columns: {missing}")

    print(f"[Trainer] Loaded dataset: {df.shape[0]} rows, {df.shape[1]} columns")
    return df


# ---------------------------------------------------------------------------
# Main training function
# ---------------------------------------------------------------------------

def train(
    data_path: str = DATA_PATH,
    model_path: str = MODEL_PATH,
    test_size: float = 0.20,
    seed: int = RANDOM_SEED,
) -> Pipeline:
    """
    Full training pipeline.

    Args:
        data_path  : Path to the CSV dataset.
        model_path : Where to save the trained joblib model.
        test_size  : Fraction of data used for testing (default 20%).
        seed       : Random state for reproducibility.

    Returns:
        Trained scikit-learn Pipeline object.
    """
    df = _load_dataset(data_path)

    X = df[FEATURE_COLS].values
    y = df[TARGET_COL].values

    # 80 / 20 stratified split.
    X_train, X_test, y_train, y_test = train_test_split(
        X, y,
        test_size=test_size,
        random_state=seed,
        stratify=y,
    )
    print(f"[Trainer] Train set: {X_train.shape[0]}  |  Test set: {X_test.shape[0]}")

    # Pipeline: scaler + Random Forest.
    pipeline = Pipeline([
        ("scaler", StandardScaler()),
        ("classifier", RandomForestClassifier(
            n_estimators=200,
            max_depth=None,           # Grow trees fully.
            min_samples_split=4,
            min_samples_leaf=2,
            max_features="sqrt",
            class_weight="balanced",
            random_state=seed,
            n_jobs=-1,
        )),
    ])

    pipeline.fit(X_train, y_train)

    # ------------------------------------------------------------------
    # Evaluation
    # ------------------------------------------------------------------
    y_pred = pipeline.predict(X_test)
    acc = accuracy_score(y_test, y_pred)

    print("\n" + "=" * 60)
    print("  CLASSIFICATION REPORT")
    print("=" * 60)
    print(classification_report(y_test, y_pred, target_names=CLASS_NAMES))

    print("CONFUSION MATRIX")
    cm = confusion_matrix(y_test, y_pred)
    cm_df = pd.DataFrame(cm, index=CLASS_NAMES, columns=CLASS_NAMES)
    print(cm_df.to_string())

    print(f"\n  Test Accuracy : {acc * 100:.2f}%")

    # 5-fold cross-validation on the full training set.
    cv_scores = cross_val_score(pipeline, X_train, y_train, cv=5, scoring="accuracy")
    print(f"  CV Accuracy   : {cv_scores.mean() * 100:.2f}% +/- {cv_scores.std() * 100:.2f}%")
    print("=" * 60)

    # Feature importances from the Random Forest.
    rf: RandomForestClassifier = pipeline.named_steps["classifier"]
    importances = rf.feature_importances_
    print("\n  FEATURE IMPORTANCES")
    for feat, imp in sorted(zip(FEATURE_COLS, importances), key=lambda x: -x[1]):
        print(f"    {feat:<20s}: {imp:.4f}")

    # ------------------------------------------------------------------
    # Persist model
    # ------------------------------------------------------------------
    os.makedirs(os.path.dirname(os.path.abspath(model_path)), exist_ok=True)
    joblib.dump(pipeline, model_path)
    print(f"\n[Trainer] Model saved -> {os.path.abspath(model_path)}")

    return pipeline


# ---------------------------------------------------------------------------
# CLI entry-point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    train()
